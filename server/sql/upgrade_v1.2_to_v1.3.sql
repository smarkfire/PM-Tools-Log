  id         SERIAL PRIMARY KEY,
  user_id    INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  todo_date  DATE        NOT NULL,
  content    TEXT        NOT NULL,
  status     VARCHAR(20) NOT NULL DEFAULT 'pending', -- pending 未完成 / done 已完成
